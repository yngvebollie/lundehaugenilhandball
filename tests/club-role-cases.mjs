import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
export async function checkClubRole(pg,login,uuid,team){
  await pg.exec("reset role;create table auth.sessions(id uuid primary key,user_id uuid references auth.users)");
  await pg.exec(await readFile(new URL("../supabase/migrations/20261107201028_club_user_directory.sql",import.meta.url),"utf8"));
  const session=uuid(901),another=uuid(902),claims=id=>pg.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({session_id:id})]);
  const role=mode=>pg.query("select beta_club_role($1) v",[mode]).then(r=>r.rows[0].v);
  const directory=()=>pg.query("select beta_club_directory() v").then(r=>r.rows[0].v);
  await pg.query("insert into nhf_private.club_admins values($1)",[uuid(1)]);
  await pg.query("insert into auth.sessions values($1,$3),($2,$3)",[session,another,uuid(1)]);
  await pg.exec("set role authenticated");await login(1);await claims(session);
  assert.deepEqual(await role("read"),{eligible:true,active:false});const own=await directory();
  assert.ok(!own.teams.some(t=>t.id===uuid(20)));assert.ok(own.teams.some(t=>t.id===team));
  assert.deepEqual(await role("club"),{eligible:true,active:true});const club=await directory();
  assert.ok(club.teams.some(t=>t.id===uuid(20)));assert.ok(club.members.some(m=>m.team===uuid(20)));
  assert.ok(!JSON.stringify(club).includes('"token"'));
  await claims(another);assert.equal((await role("read")).active,false);
  await claims(session);await login(4);await assert.rejects(role("club"));assert.ok(!(await directory()).teams.some(t=>t.id===uuid(10)));
  await login(7);await assert.rejects(directory());await assert.rejects(role("club"));
  await login(1);await role("coach");assert.ok(!(await directory()).teams.some(t=>t.id===uuid(20)));

  await pg.exec("reset role");
  await pg.exec(await readFile(new URL("../supabase/migrations/20261123093000_club_registration.sql",import.meta.url),"utf8"));
  await pg.exec("alter table auth.users add column if not exists created_at timestamptz default now()");
  await pg.exec(await readFile(new URL("../supabase/migrations/20261123110000_club_owner_activity.sql",import.meta.url),"utf8"));
  await pg.query("insert into nhf_private.club_approval_owner(account) values($1)",[uuid(1)]);
  await pg.query("insert into nhf_private.club_admins values($1)",[uuid(4)]);
  const otherAdminSession=uuid(903),applicant=uuid(905),unverified=uuid(906),declined=uuid(907);
  await pg.query("insert into auth.sessions values($1,$2)",[otherAdminSession,uuid(4)]);
  await pg.query("insert into auth.users(id,email,email_confirmed_at) values($1,'sandnes@test.local',now()),($2,'unverified@test.local',null),($3,'declined@test.local',now())",[applicant,unverified,declined]);
  await pg.exec("set role authenticated");
  const apply=()=>pg.query("select beta_request_club('Sandnes','Trener') v").then(r=>r.rows[0].v);
  const pending=()=>pg.query("select beta_pending_club_requests() v").then(r=>r.rows[0].v);
  const count=()=>pg.query("select beta_club_request_count() v").then(r=>r.rows[0].v);
  const activity=()=>pg.query("select beta_club_owner_activity() v").then(r=>r.rows[0].v);
  const decide=(id,approve)=>pg.query("select beta_decide_club_request($1,$2) v",[id,approve]).then(r=>r.rows[0].v);
  await login(unverified);await assert.rejects(apply());
  await login(applicant);assert.equal(await apply(),"pending");assert.equal(await apply(),"pending");
  await login(declined);assert.equal(await apply(),"pending");
  assert.equal((await pg.query("select count(*) n from beta_teams")).rows[0].n,0);
  await assert.rejects(pending());await assert.rejects(decide(applicant,true));
  assert.equal(await count(),null);await assert.rejects(activity());
  await login(4);await claims(otherAdminSession);await role("club");
  await assert.rejects(pending());await assert.rejects(decide(applicant,true));
  assert.equal(await count(),null);await assert.rejects(activity());
  await role("coach");
  await login(1);await claims(session);
  await assert.rejects(pending());await assert.rejects(activity());assert.equal((await count()).pending,2);
  await role("club");assert.equal((await pending()).length,2);
  const sandnes=await decide(applicant,true);
  assert.equal(await decide(applicant,true),sandnes);
  assert.equal(await decide(declined,false),null);
  assert.equal((await pending()).length,0);
  assert.equal((await count()).pending,0);
  assert.ok((await activity()).some(row=>row.event==="approved"&&row.club==="Sandnes"));
  assert.ok((await activity()).some(row=>row.event==="user"&&row.club==="Sandnes"));
  await role("coach");
  await login(applicant);
  assert.equal((await pg.query("select beta_club_request_status() v")).rows[0].v,"approved");
  assert.deepEqual((await directory()).teams,[{id:sandnes,name:"Sandnes",admin:true}]);
  await assert.rejects(pg.query("update beta_teams set discoverable=true where id=$1",[sandnes]));
  await login(declined);
  assert.equal((await pg.query("select beta_club_request_status() v")).rows[0].v,"declined");
  await login(4);
  assert.ok(!(await directory()).teams.some(t=>t.id===sandnes));
  await login(1);await claims(session);
}

const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE||"playwright");
const assert=require("node:assert/strict");
(async()=>{
  const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||"msedge"});
  try{
    const context=await browser.newContext();
    context.setDefaultTimeout(10000);
    const coach=await context.newPage(), athlete=await context.newPage();
    const base=process.env.BETA_TEST_URL||"http://127.0.0.1:3217";
    await coach.goto(base+"/login");
    await coach.getByRole("button",{name:"Open workspace"}).click();
    await coach.getByLabel("Team name",{exact:true}).fill("Development squad");
    await coach.getByRole("button",{name:"Create team",exact:true}).click();
    await coach.getByLabel("Current team").getByRole("option",{name:"Development squad"}).waitFor({state:"attached"});
    await coach.getByLabel("Invite email").fill("tester@example.test");
    await coach.getByRole("button",{name:"Create invitation link"}).click();
    const link=await coach.getByLabel(/Invitation link ·/).inputValue();
    await athlete.setViewportSize({width:390,height:844});
    await athlete.goto(link);
    await athlete.getByLabel("Your name").fill("Pilot Player");
    await athlete.getByLabel("Email",{exact:true}).fill("tester@example.test");
    await athlete.getByRole("button",{name:"Accept invitation"}).click();
    await athlete.getByRole("button",{name:"Profile",exact:true}).click();
    await athlete.getByLabel("Playing position").fill("Left wing");
    await athlete.getByLabel("About me").fill("Preparing for match week.");
    const pic=await athlete.evaluate(()=>document.createElement("canvas").toDataURL("image/png").split(",")[1]);
    await athlete.getByLabel("Profile photo").setInputFiles({name:"portrait.png",mimeType:"image/png",buffer:Buffer.from(pic,"base64")});
    await athlete.getByAltText("Profile portrait").waitFor();
    await athlete.getByRole("button",{name:"Save profile"}).click();
    await athlete.getByText("Profile saved.").waitFor();
    await coach.getByText("Left wing",{exact:true}).waitFor();
    await coach.getByLabel("Session title").fill("Rotation block");
    await coach.getByLabel("Exercise name",{exact:true}).fill("Pallof hold");
    await coach.getByLabel("Sets, reps or time").fill("3 x 20 sec");
    await coach.getByLabel("Primary focus").selectOption("Core");
    await coach.getByRole("button",{name:"Save and add exercise"}).click();
    await coach.getByRole("button",{name:"Save current session"}).click();
    await coach.getByText(/Session saved. It is also/).waitFor();
    await coach.reload();
    const planner=coach.locator("#weekly");
    await planner.getByText("Schedule training or event",{exact:true}).click();
    await planner.getByLabel("Session to schedule").selectOption({label:"Rotation block"});
    await planner.getByRole("button",{name:/Schedule session ·/}).click();
    await planner.getByText(/Rotation block scheduled/).waitFor();
    await planner.getByLabel("Activity type").selectOption("Practice");
    await planner.getByLabel("Activity title").fill("Court practice");
    await planner.getByLabel("Number of weekly occurrences").fill("3");
    await planner.getByRole("button",{name:/Schedule practice ·/}).click();
    await planner.getByText(/Court practice scheduled for 3 weeks/).waitFor();
    await planner.getByLabel("Activity type").selectOption("Game");
    await planner.getByLabel("Activity title").fill("Away fixture");
    await planner.getByLabel("Number of weekly occurrences").fill("1");
    await planner.getByRole("button",{name:/Schedule game ·/}).click();
    await planner.getByText(/Away fixture scheduled/).waitFor();
    await athlete.getByRole("button",{name:"Today",exact:true}).click();
    await athlete.getByRole("checkbox",{name:/Pallof hold/}).check();
    await athlete.getByLabel("Attended game").check();
    await athlete.getByRole("button",{name:"Plan",exact:true}).click();
    await athlete.getByText("Add to my schedule",{exact:true}).click();
    const personal=athlete.locator("#weekly");
    await personal.getByLabel("Activity title").fill("Personal mobility");
    await personal.getByLabel("Session exercises").fill("Stretch 2 x 20 sec");
    await personal.getByRole("button",{name:/Schedule session · Personal/}).click();
    await personal.getByText(/Personal mobility scheduled/).waitFor();
    assert.ok(await athlete.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const playerId=await athlete.evaluate(()=>sessionStorage.getItem("nhf-persona"));
    await planner.getByLabel("Planner athlete").selectOption(playerId);
    await planner.getByRole("row").filter({has:coach.getByRole("rowheader",{name:"Core",exact:true})}).getByText("3 / 3").waitFor();
    await planner.getByText("60 / 120",{exact:true}).waitFor();
    await planner.getByRole("button",{name:"Next week"}).click();
    await planner.locator(".week-item").getByText("Court practice",{exact:true}).waitFor();
    assert.equal(await planner.locator(".week-item").getByText("Away fixture",{exact:true}).count(),0);
    await coach.getByLabel("Current team").selectOption("demo");
    await coach.getByText("Liv Berg",{exact:true}).first().waitFor({state:"attached"});
    assert.equal(await coach.locator(".week-item").getByText("Court practice",{exact:true}).count(),0);
    console.log("PASS: sign-in, teams, invite acceptance, profile photo, saved exercise and session, weekly practice and game, personal plan, workload totals and team switching.");
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
